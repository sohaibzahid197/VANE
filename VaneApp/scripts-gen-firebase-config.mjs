// Generates src/firebaseConfig.ts from the platform Firebase config files.
// Those files are gitignored, so the generated module is too; run this after
// a fresh clone. Client API keys are not secrets — they identify the project
// and are protected by Firestore rules — but they stay out of git anyway.
import { readFileSync, writeFileSync } from 'node:fs';

const gs = JSON.parse(readFileSync('android/app/google-services.json', 'utf8'));
const projectId = gs.project_info.project_id;
const apiKey = gs.client[0].api_key[0].current_key;

writeFileSync(
  'src/firebaseConfig.ts',
  `// GENERATED by scripts-gen-firebase-config.mjs — do not edit by hand.\n` +
    `export const FIREBASE_PROJECT_ID = '${projectId}';\n` +
    `export const FIREBASE_API_KEY = '${apiKey}';\n`,
);
console.log(`wrote src/firebaseConfig.ts for ${projectId}`);
